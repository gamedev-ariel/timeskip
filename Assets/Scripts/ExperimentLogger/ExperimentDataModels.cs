[Serializable]
public class ProximityApproachEvent
{
    public string type = "approach_target"; // player moved towards a nearby target
    public string scene; // area/scene label (e.g., "forest" | "river")
    public string targetType; // "fish" | "blueberry"
    public string targetId;   // name or unique id
    public Vector2 targetPos; // world position of target at time of log
    public Vector2 playerPos; // player world position
    public float distance;    // current distance to target (world units)
    public float threshold;   // proximity threshold used (world units)
    public string time;       // ISO timestamp
    public float timeSinceStart;
    public float timeSinceSceneStart;
}

