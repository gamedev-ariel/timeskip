[Serializable]
public class SceneSection
{
    public string scene; // scene name (e.g., "start", "river", "forest", "dwarf")
    public List<SceneEvent> events = new List<SceneEvent>();
    public List<KeyEvent> keys = new List<KeyEvent>();
    public List<OutcomeEvent> outcomes = new List<OutcomeEvent>();
    public List<MinigameSection> minigames = new List<MinigameSection>();
    // River is not a minigame: store river trial logs directly under the scene section
    public List<RiverJumpStartEvent> riverJumpStarts = new List<RiverJumpStartEvent>();
    public List<RiverJumpLandEvent> riverJumpLands = new List<RiverJumpLandEvent>();
    public List<RiverCollisionEvent> riverCollisions = new List<RiverCollisionEvent>();
    public List<RiverFinishEvent> riverFinish = new List<RiverFinishEvent>();
    // Fish spawns (timestamp when a fish becomes active/seen in the scene)
    public List<FishSpawnEvent> fishSpawns = new List<FishSpawnEvent>();
    // Proximity/approach logs (player moving towards a nearby fish/blueberry)
    public List<ProximityApproachEvent> approaches = new List<ProximityApproachEvent>();
}

