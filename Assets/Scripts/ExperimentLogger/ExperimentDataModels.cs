using System;
using System.Collections.Generic;
using UnityEngine;

// Legacy click structure (kept for reference but no longer used except for MemoryGame-specific clicks)
[Serializable]
public class ClickEvent
{
    public string time;
    public float timeSinceStart;
    public float timeSinceSceneStart;
    public string scene;
    public string area;
    public string target;
    public string inputType;
    public float x;
    public float y;
}

[Serializable]
public class OutcomeEvent
{
    public string time;
    public float timeSinceStart;
    public float timeSinceSceneStart;
    public float timeSinceMinigameStart; // 0 if no active minigame
    public string scene; // unity scene name for explicit attribution
    public string area;
    public string outcome;
    public string reason;
    public Vector2 playerPos; // player world position (excluded in dwarf/memory scenes)
}

[Serializable]
public class KeyEvent
{
    public string time;
    public float timeSinceStart;
    public float timeSinceSceneStart;
    public string scene; // unity scene name for explicit attribution
    public string type = "input";     // constant: "input"
    public string device = "keyboard"; // constant: "keyboard"
    public string action;        // "down" | "up" | "repeat"
    public string key;           // e.g., "Space", "A", "LeftArrow"
    public float heldMs;         // duration in ms for "up" events; 0 for "down"
    public bool isRepeat;        // true if this event was generated by key-repeat
    public Vector2 playerPos;    // player world position (excluded in dwarf/memory scenes)
}

[Serializable]
public class SceneEvent
{
    public string time;
    public float timeSinceStart;
    public float timeSinceSceneStart;
    public string scene; // unity scene name for explicit attribution
    public string eventType; // scene_enter | scene_exit
    public string sceneVisitId; // GUID for a single continuous visit to a scene
    public string fromScene; // optional, previous scene name (grouped)
    public string toScene;   // optional, next/current scene name (grouped)
    public Vector2 playerPos; // player world position (excluded in dwarf/memory scenes)
}

[Serializable]
public class MiniGameEvent
{
    public string time;
    public float timeSinceStart;
    public float timeSinceSceneStart;
    public float timeSinceMinigameStart; // 0 at minigame start
    public string scene; // unity scene name for explicit attribution
    public string eventType; // start/end/paused/resumed/custom
    public string reason;    // optional info (e.g., why ended)
}

[Serializable]
public class MemoryClickEvent
{
    public string time;
    public float timeSinceStart;
    public float timeSinceSceneStart;
    public float timeSinceMinigameStart;
    public string scene; // unity scene name for explicit attribution
    public int level;
    public string result;   // "right" | "wrong"
    public int livesLeft;   // memory game only
}

[Serializable]
public class MemoryLevelResult
{
    public string time;
    public float timeSinceStart;
    public float timeSinceSceneStart;
    public float timeSinceMinigameStart;
    public string scene; // unity scene name for explicit attribution
    public int level;
    public string result;   // "win" | "fail"
    public string reason;   // optional context
    public int livesLeft;   // memory game only
}

[Serializable]
public class MinigameSection
{
    public string name; // minigame name, e.g., "memory"
    public List<MiniGameEvent> events = new List<MiniGameEvent>();
    public List<OutcomeEvent> outcomes = new List<OutcomeEvent>();
    public List<MemoryClickEvent> clicks = new List<MemoryClickEvent>();
    public List<MemoryLevelResult> levelResults = new List<MemoryLevelResult>();
    // Dwarf memory game: mouse inputs during the minigame
    public List<MouseInputEvent> mouseInputs = new List<MouseInputEvent>();
    // Summary result (to avoid ambiguity when reading per-level items)
    public string finalResult;   // "win" | "fail" | null
    public string finalReason;   // e.g., "game_over" | "all_levels_cleared"
    public string finishedTime;  // ISO timestamp when ended
    public float finishedSinceStart;
    public float finishedSinceSceneStart;
    public float finishedSinceMinigameStart;
    // Trial-level logging containers
    public List<ForestItemSpawnEvent> forestItemSpawns = new List<ForestItemSpawnEvent>();
    public List<ForestItemResolveEvent> forestItemResolves = new List<ForestItemResolveEvent>();
    public List<RiverJumpStartEvent> riverJumpStarts = new List<RiverJumpStartEvent>();
    public List<RiverJumpLandEvent> riverJumpLands = new List<RiverJumpLandEvent>();
    public List<RiverCollisionEvent> riverCollisions = new List<RiverCollisionEvent>();
    public List<RiverFinishEvent> riverFinish = new List<RiverFinishEvent>();
    // Dwarf memory game: trial stimulus/response logs per level
    public List<DwarfTrialStartEvent> dwarfTrialStarts = new List<DwarfTrialStartEvent>();
    public List<DwarfTrialResponseEvent> dwarfTrialResponses = new List<DwarfTrialResponseEvent>();
}

